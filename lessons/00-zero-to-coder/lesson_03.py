
# Lesson 3: Variables Are Labels

character_name = "Nova"
energy = 100
stars = 0

print("Starting status:")
print(f"Character: {character_name}")
print(f"Energy: {energy}")
print(f"Stars: {stars}")

# Update the character's status
energy = energy - 35
stars = stars + 7

print("\nUpdated status:")
print(f"Character: {character_name}")
print(f"Energy: {energy}")
print(f"Stars: {stars}")